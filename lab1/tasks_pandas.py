import pandas as pd
import io

df = pd.read_csv("titanic.csv", sep='\t')

print("Распределение по полу:\n", df['Sex'].value_counts())
print("\nПассажиры по классам:\n", df['Pclass'].value_counts().sort_index())
print("\nСтатистика по возрасту:\n", df['Age'].agg(['mean', 'min', 'max']))
print("\nКоличество выживших:", df['Survived'].sum())
print("\nСредний возраст по классам:\n", df.groupby('Pclass')['Age'].mean())